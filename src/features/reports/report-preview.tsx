"use client";

import { useQuery } from "@tanstack/react-query";
import { Box, Download, FileSpreadsheet, Printer, X } from "lucide-react";
import { Logo } from "@/components/layout/logo";
import { Button } from "@/components/ui/button";
import { Card, CardHeader } from "@/components/ui/card";
import { ErrorState, LoadingState } from "@/components/ui/states";
import { VEHICLE_TYPES, labelOf } from "@/lib/constants";
import { downloadFile, toCsv } from "@/lib/csv";
import { formatDate, formatNumber } from "@/lib/utils";
import { REPORT_TYPES, reportsService, type ReportDetail } from "./api";
import { DistancePerVehicleChart, TripStatusDonut } from "./report-charts";

const PRINT_CLASS = "bm-print-report";
const PRINT_ID = "report-print-area";

/** Prints only the report document; "Download (PDF)" uses the same dialog's Save as PDF. */
function printReport() {
  const root = document.documentElement;
  const done = () => {
    root.classList.remove(PRINT_CLASS);
    window.removeEventListener("afterprint", done);
  };
  root.classList.add(PRINT_CLASS);
  window.addEventListener("afterprint", done);
  window.print();
}

/** CSV of the report's figures (opens in Excel). */
export function exportReportCsv(report: ReportDetail) {
  const { preview: p } = report;
  const rows: (string | number | null)[][] = [
    [report.name],
    ["Type", report.type_label],
    ["Period", `${p.period.from} to ${p.period.to}`],
    ["Generated by", report.generated_by?.name ?? ""],
    [],
    ["Total Vehicles", p.summary.total_vehicles],
    ["Active Vehicles", p.summary.active_vehicles],
    ["Total Distance (km)", p.summary.total_distance_km],
    ["Total Trips", p.summary.total_trips],
    [],
    ["Vehicle No.", "Type", "Total Distance (km)", "Total Trips", "Days on Trips", "Utilization Rate (%)"],
    ...p.vehicles.map((v) => [v.plate_number, labelOf(VEHICLE_TYPES, v.vehicle_type ?? ""), v.distance_km, v.trips, v.active_days, v.utilization_rate]),
    [],
    ["Trip Status", "Trips"],
    ...p.trip_status.map((s) => [s.label, s.count]),
  ];
  const slug = report.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "report";
  downloadFile(`blitzmove-${slug}-${p.period.from}-${p.period.to}.csv`, toCsv(rows));
}

export function ReportPreview({ reportId, onClose }: { reportId: number; onClose: () => void }) {
  const query = useQuery({ queryKey: ["reports", reportId], queryFn: () => reportsService.get(reportId).then((r) => r.data) });
  const report = query.data;

  return (
    <Card className="flex min-w-0 flex-col">
      <CardHeader
        icon={<Box />}
        title="Report Preview"
        action={
          <button type="button" onClick={onClose} className="-mr-1 rounded-lg p-1.5 text-ink-500 hover:bg-ink-100 hover:text-ink-800" aria-label="Close preview">
            <X className="h-5 w-5" />
          </button>
        }
      />
      <div className="flex-1 p-4">
        {query.isLoading ? <LoadingState label="Building report…" /> : query.error ? <ErrorState message={query.error.message} onRetry={() => query.refetch()} /> : report && <ReportDocument report={report} />}
      </div>
      {report && (
        <div className="grid grid-cols-1 gap-2 border-t border-ink-100 px-4 py-3 sm:grid-cols-3">
          <Button variant="secondary" size="sm" className="h-9 px-2" onClick={printReport} title="Opens the print dialog; choose “Save as PDF”">
            <Download className="h-4 w-4" /> Download (PDF)
          </Button>
          <Button variant="secondary" size="sm" className="h-9 px-2" onClick={() => exportReportCsv(report)} title="CSV file that opens in Excel">
            <FileSpreadsheet className="h-4 w-4" /> Download (Excel)
          </Button>
          <Button variant="secondary" size="sm" className="h-9 px-2" onClick={printReport}>
            <Printer className="h-4 w-4" /> Print
          </Button>
        </div>
      )}
      {/* Print only the report document. */}
      <style>{`@media print {
        html.${PRINT_CLASS} body * { visibility: hidden !important; }
        html.${PRINT_CLASS} #${PRINT_ID}, html.${PRINT_CLASS} #${PRINT_ID} * { visibility: visible !important; }
        html.${PRINT_CLASS} #${PRINT_ID} { position: absolute; inset: 0 auto auto 0; width: 100%; border: 0; box-shadow: none; }
      }`}</style>
    </Card>
  );
}

function ReportDocument({ report }: { report: ReportDetail }) {
  const { preview: p } = report;
  const title = REPORT_TYPES[report.type]?.title ?? report.name;
  const withDistance = p.vehicles.filter((v) => v.distance_km != null).map((v) => ({ plate: v.plate_number, km: v.distance_km! }));
  const tiles = [
    { label: "Total Vehicles", value: formatNumber(p.summary.total_vehicles) },
    { label: "Active Vehicles", value: formatNumber(p.summary.active_vehicles) },
    { label: "Total Distance", value: p.summary.total_distance_km == null ? "—" : `${formatNumber(p.summary.total_distance_km)} km` },
    { label: "Total Trips", value: formatNumber(p.summary.total_trips) },
  ];

  return (
    <div id={PRINT_ID} className="@container rounded-lg border border-ink-100 bg-white p-4 text-ink-900">
      <div className="flex items-start justify-between gap-3 border-b border-ink-100 pb-3">
        <Logo className="w-24 shrink-0" />
        <div className="min-w-0 text-right">
          <p className="text-base font-bold">{title}</p>
          {report.name !== title && <p className="truncate text-xs text-ink-600">{report.name}</p>}
          <p className="text-xs text-ink-500">
            {formatDate(p.period.from, "MMMM d, yyyy")} – {formatDate(p.period.to, "MMMM d, yyyy")}
          </p>
        </div>
      </div>

      <div className="mt-3 grid grid-cols-2 gap-2 @md:grid-cols-4">
        {tiles.map((t) => (
          <div key={t.label} className="rounded-md border border-ink-100 bg-ink-50 px-2.5 py-2">
            <p className="truncate text-[0.68rem] text-ink-500">{t.label}</p>
            <p className="text-sm font-bold">{t.value}</p>
          </div>
        ))}
      </div>

      <p className="mt-4 mb-1.5 text-xs font-semibold">Vehicle Utilization</p>
      <div className="overflow-x-auto">
        <table className="w-full min-w-[22rem] text-[0.7rem] [&_td]:whitespace-nowrap">
          <thead className="bg-ink-50 text-left text-ink-600">
            <tr>
              <th className="px-2 py-1.5 font-medium">Vehicle No.</th>
              <th className="px-2 py-1.5 font-medium">Type</th>
              <th className="px-2 py-1.5 text-right font-medium">Total Distance (km)</th>
              <th className="px-2 py-1.5 text-right font-medium">Total Trips</th>
              <th className="px-2 py-1.5 text-right font-medium" title="Days with a trip on the road ÷ days in the period">
                Utilization Rate
              </th>
            </tr>
          </thead>
          <tbody className="divide-y divide-ink-100">
            {p.vehicles.length === 0 ? (
              <tr>
                <td colSpan={5} className="px-2 py-4 text-center text-ink-500">
                  No vehicles match this report.
                </td>
              </tr>
            ) : (
              p.vehicles.map((v) => (
                <tr key={v.id}>
                  <td className="px-2 py-1.5 font-medium">{v.plate_number}</td>
                  <td className="px-2 py-1.5 text-ink-600">{v.vehicle_type ? labelOf(VEHICLE_TYPES, v.vehicle_type) : "—"}</td>
                  <td className="px-2 py-1.5 text-right tabular-nums">{formatNumber(v.distance_km)}</td>
                  <td className="px-2 py-1.5 text-right tabular-nums">{v.trips}</td>
                  <td className="px-2 py-1.5 text-right tabular-nums">{formatNumber(v.utilization_rate, 1)}%</td>
                </tr>
              ))
            )}
          </tbody>
        </table>
      </div>
      <p className="mt-1 text-[0.65rem] text-ink-500">
        Distance from fuel-record odometer readings. Utilization = days with a trip on the road ÷ {p.period.days} days.
      </p>

      <div className="mt-4 grid gap-3 @xs:grid-cols-2">
        <div className="min-w-0 rounded-md border border-ink-100 p-2.5">
          <p className="mb-1.5 text-xs font-semibold">Distance per Vehicle</p>
          {withDistance.length ? (
            <div style={{ height: Math.max(96, withDistance.length * 22) }}>
              <DistancePerVehicleChart data={withDistance} />
            </div>
          ) : (
            <p className="rounded-md bg-ink-50 px-3 py-6 text-center text-[0.7rem] text-ink-500">No odometer readings in this period.</p>
          )}
        </div>
        <div className="min-w-0 rounded-md border border-ink-100 p-2.5">
          <p className="mb-1.5 text-xs font-semibold">Trip Status Distribution</p>
          <TripStatusDonut data={p.trip_status} compact />
        </div>
      </div>
    </div>
  );
}
